// Loads PGlite in the browser from untouched files under /public/pglite, imported natively at
// runtime so no bundler transforms the Emscripten build. This is the only place that knows how
// the browser gets Postgres; moving it to a Worker or a server changes nothing above it.
import type { PGliteLike } from "../kernel/local";

type PGliteConstructor = new (dataDirOrOptions?: string | Record<string, unknown>, options?: Record<string, unknown>) => PGliteLike & {
  dumpDataDir(compression?: "gzip" | "none"): Promise<Blob>;
  close(): Promise<void>;
};

let loaded: Promise<PGliteConstructor> | undefined;

export function loadPGlite(): Promise<PGliteConstructor> {
  loaded ??= import(/* webpackIgnore: true */ /* turbopackIgnore: true */ "/pglite/index.js" as string).then(
    (mod: { PGlite: PGliteConstructor }) => mod.PGlite,
  );
  return loaded;
}

// The kernel migrations, in order, as generated by scripts/sync-browser-assets.mjs.
export async function kernelMigrations(): Promise<string[]> {
  const response = await fetch("/kernel/migrations.json");
  if (!response.ok) throw new Error(`kernel migrations unavailable (${response.status})`);
  const list = (await response.json()) as { name: string; sql: string }[];
  return list.map((m) => m.sql);
}
