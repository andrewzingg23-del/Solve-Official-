// The World, tested in a real browser against the built app.
//   npm run build && npm run test:world [-- --update-baseline]
// Proves more than "the globe appeared": the snapshot and manifest agree; the browser's kernel
// reproduces Arcadia's semantic digest; every rendered thing is a canonical ref; a private record
// never reaches the browser's view; a click selects the canonical entity; the full loop changes the
// World through recorded consequence. Records performance (boot, load, scene, frames, memory,
// query latency) and compares it with perf/world-baseline.json (warnings, never failures: timings
// depend on the machine).
import { spawn } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { createServer } from "node:net";
import { join } from "node:path";
import { chromium } from "playwright-core";

const root = process.cwd();
const failures = [];
const check = (ok, what) => {
  console.log(`${ok ? "ok  " : "FAIL"} ${what}`);
  if (!ok) failures.push(what);
};
const sha256 = (data) => createHash("sha256").update(data).digest("hex");

// 1. The snapshot is what its manifest says it is, built by this kernel.
const manifest = JSON.parse(readFileSync(join(root, "public/arcadia/manifest.json"), "utf8"));
const snapshot = readFileSync(join(root, "public/arcadia/snapshot.tgz"));
check(sha256(snapshot) === manifest.arcadia.snapshot && manifest.version === manifest.arcadia.snapshot.slice(0, 16), "snapshot bytes match the manifest");
const migrationsDir = join(root, "supabase/migrations");
const files = readdirSync(migrationsDir).filter((f) => f.endsWith(".sql")).sort();
const kernel = sha256(files.map((f) => `${f}\n${readFileSync(join(migrationsDir, f), "utf8")}`).join("\n"));
check(kernel === manifest.arcadia.kernel, "snapshot was generated by the current kernel migrations");
check(Boolean(manifest.arcadia.generator && manifest.arcadia.seed && manifest.arcadia.digest), `provenance: ${manifest.arcadia.generator}, seed ${manifest.arcadia.seed}`);

const port = await new Promise((resolve) => {
  const s = createServer().listen(0, () => {
    const p = s.address().port;
    s.close(() => resolve(p));
  });
});
const server = spawn(process.execPath, [join(root, "node_modules/next/dist/bin/next"), "start", "-p", String(port)], { cwd: root, stdio: "ignore" });
const url = `http://localhost:${port}/`;
for (let i = 0; i < 120; i++) {
  try {
    if ((await fetch(url)).ok) break;
  } catch {
    // starting
  }
  await new Promise((r) => setTimeout(r, 250));
}

function chromiumPath() {
  if (process.env.CHROMIUM_PATH) return process.env.CHROMIUM_PATH;
  const base = process.env.PLAYWRIGHT_BROWSERS_PATH ?? "/opt/pw-browsers";
  if (!existsSync(base)) return undefined;
  const dir = readdirSync(base).filter((d) => /^chromium-\d+$/.test(d)).sort().at(-1);
  return dir ? join(base, dir, "chrome-linux/chrome") : undefined;
}

const browser = await chromium.launch({ executablePath: chromiumPath(), args: ["--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--enable-precise-memory-info"] });
const perf = {};
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = [];
  page.on("pageerror", (e) => errors.push(`pageerror: ${e.message}`));
  page.on("console", (m) => m.type() === "error" && errors.push(`console: ${m.text().slice(0, 300)}`));

  const started = Date.now();
  await page.goto(url);
  await page.getByText("Who should represent you in SOV?").waitFor({ timeout: 120_000 });
  perf.firstViewMs = Date.now() - started;

  // 2. Browser parity: the kernel this browser booted reproduces Arcadia exactly.
  const digest = await page.evaluate(() => window.__sov.digest());
  check(digest.digest === manifest.arcadia.digest, "browser kernel reproduces the Arcadia semantic digest");
  check(JSON.stringify(digest.tables) === JSON.stringify(manifest.arcadia.tables), "browser kernel row counts match the manifest");

  await page.getByRole("button", { name: /Create my AI/ }).click();
  await page.getByLabel("Description").fill("Intelligent, calm, warm, dark hair, minimalist futuristic clothing");
  await page.getByRole("button", { name: "Choose" }).click();
  await page.getByRole("button", { name: "Enter Earth" }).click();
  const horizon = page.getByPlaceholder("What do you want to make real?");
  await horizon.waitFor();
  await page.waitForFunction(() => (window.__sov?.scene()?.renderedRefs().length ?? 0) > 0, null, { timeout: 120_000 });

  // 3. Identity and authorized visibility: one entity, many representations.
  const scene = await page.evaluate(() => {
    const s = window.__sov;
    return { rendered: s.scene().renderedRefs(), markers: s.view().markers.map((m) => m.ref), metrics: s.metrics };
  });
  check(scene.rendered.length === scene.markers.length && scene.rendered.every((r) => scene.markers.includes(r)), `scene draws exactly the spatial view (${scene.rendered.length} markers)`);
  check(scene.rendered.every((r) => /^entity:[0-9a-f-]{36}$/.test(r)), "every rendered thing is a canonical entity ref");
  check(Object.values(manifest.orgs).every((o) => scene.rendered.includes(`entity:${o.entityId}`)), "every Arcadia organization is on Earth at its own id");
  const hidden = `entity:${manifest.privateEntityId}`;
  const leaked = await page.evaluate((ref) => {
    const v = window.__sov.view();
    return v.markers.some((m) => m.ref === ref) || window.__sov.scene().renderedRefs().includes(ref) || document.body.innerText.includes("second line (confidential)");
  }, hidden);
  check(!leaked, "the private record never reaches the browser's view");
  Object.assign(perf, { bootMs: scene.metrics.boot.total, loadMs: scene.metrics.loadMs, sceneInitMs: scene.metrics.scene?.initMs, markers: scene.rendered.length });

  // 4. Selection resolves to canonical ids; additive picks build a set.
  const halden = `entity:${manifest.orgs.halden.entityId}`;
  const kestrel = `entity:${manifest.orgs.kestrel.entityId}`;
  await page.evaluate((ref) => window.__sov.scene().focusEntity(ref), halden);
  // Click where the scene says the entity is, once the camera has settled.
  const settled = async (ref) => {
    // Software WebGL can render a frame or two a second: require the position to hold for 2 s.
    let last = null;
    let still = 0;
    for (let i = 0; i < 60 && still < 4; i++) {
      await page.waitForTimeout(500);
      const p = await page.evaluate((r) => window.__sov.scene().screenPosition(r), ref);
      still = p && last && Math.abs(p.x - last.x) < 0.5 && Math.abs(p.y - last.y) < 0.5 ? still + 1 : 0;
      last = p;
    }
    return last;
  };
  const clickAt = async (ref, modifiers) => {
    const p = await settled(ref);
    const onCanvas = p && (await page.evaluate(({ x, y }) => document.elementFromPoint(x, y)?.tagName === "CANVAS", p));
    if (!onCanvas) console.log(`  (${ref} is not clickable on the canvas at ${JSON.stringify(p)})`);
    for (const key of modifiers ?? []) await page.keyboard.down(key);
    if (p) await page.mouse.click(p.x, p.y);
    for (const key of modifiers ?? []) await page.keyboard.up(key);
    await page.waitForTimeout(800);
    return page.evaluate(() => window.__sov.context().currentSelectionIds);
  };
  const beforeSelection = await page.evaluate(() => window.__sov.digest());
  check(JSON.stringify(await clickAt(halden)) === JSON.stringify([halden]), "clicking Halden selects its canonical id");
  check(JSON.stringify(await clickAt(kestrel, ["Shift"])) === JSON.stringify([halden, kestrel]), "shift-click adds Kestrel: a set for \"these\"");
  await page.keyboard.press("Escape");

  // 5. Frame rate during a semantic camera move, and memory.
  const frames = await page.evaluate(
    () =>
      new Promise((resolve) => {
        let n = 0;
        const t0 = performance.now();
        window.__sov.scene().returnHome();
        const tick = () => (performance.now() - t0 < 1600 ? (n++, requestAnimationFrame(tick)) : resolve((n * 1000) / (performance.now() - t0)));
        requestAnimationFrame(tick);
      }),
  );
  perf.fps = Math.round(frames);
  perf.heapMB = await page.evaluate(() => (performance.memory ? Math.round(performance.memory.usedJSHeapSize / 1e6) : null));
  const afterSelection = await page.evaluate(() => window.__sov.digest());
  check(afterSelection.digest === beforeSelection.digest, "selecting, shift-selecting and moving the camera wrote nothing to the kernel");

  // 6. The loop: intent → route → selection → refusal → delegation → answer → commitment → World.
  const ask = async (text) => {
    const t0 = Date.now();
    await horizon.fill(text);
    await horizon.press("Enter");
    await page.waitForFunction(() => !document.querySelector('input[placeholder="What do you want to make real?"]')?.disabled, null, { timeout: 60_000 });
    await page.waitForTimeout(600);
    return Date.now() - t0;
  };
  perf.buildMs = await ask("Help me build a car company with the least upfront capital possible.");
  const world = await page.evaluate(() => window.__sov.view().offEarth.map((o) => o.title));
  await page.getByRole("button", { name: "Find them" }).first().click();
  await page.waitForTimeout(1500);
  const offEarth = await page.evaluate(() => window.__sov.view().offEarth.map((o) => o.title));
  check(offEarth.includes("Your car company") || world.includes("Your car company"), "the venture World is listed off Earth, not given coordinates");
  // The Horizon, computed from the World for the companion: the route, who acts, and why the
  // other suppliers are not routes.
  await page.getByRole("button", { name: "Cause", exact: true }).click();
  const horizonPanel = page.getByRole("region", { name: "Horizon" });
  await horizonPanel.getByText("Not a route").waitFor({ timeout: 30_000 });
  const horizonText = await horizonPanel.innerText();
  check(/disputed/.test(horizonText) && /6,000 a year, below 10,000/.test(horizonText), "the Horizon routes through Halden and says why Cobalt and Orrin are not routes");
  check(/you · allowed/i.test(horizonText) && /nova · allowed/i.test(horizonText) && /do this/i.test(horizonText), "each route step shows who acts (you, Nova) and the kernel's decision for them");
  await page.getByRole("button", { name: "Space", exact: true }).click();
  await page.getByRole("button", { name: "Index", exact: true }).click();
  await page.getByRole("navigation", { name: "World index" }).getByRole("button", { name: /Halden Works/ }).click();
  perf.refusalMs = await ask("Can they make 10,000?");
  const blocked = await page.evaluate((ref) => window.__sov.view().markers.find((m) => m.ref === ref)?.state, halden);
  check(blocked === "blocked", "a recorded refusal marks Halden as not reachable");
  await page.getByRole("button", { name: /Let your companion contact suppliers/ }).click();
  await page.waitForFunction(() => !document.querySelector('input[placeholder="What do you want to make real?"]')?.disabled, null, { timeout: 60_000 });
  perf.answerMs = await ask("Can they make 10,000?");
  check((await page.locator('[aria-live="polite"]').first().innerText()).includes("12,000"), "Halden's agent answers from its verified record");
  const commitStarted = Date.now();
  await page.getByRole("button", { name: "Accept as you" }).click();
  await page.waitForFunction((ref) => window.__sov.view().markers.find((m) => m.ref === ref)?.state === "committed", halden, { timeout: 30_000 });
  perf.commitMs = Date.now() - commitStarted;
  const committed = await page.evaluate(() => window.__sov.view().links.some((l) => l.kind === "relation" && l.style === "committed"));
  check(committed, "the agreement changes the World: Halden's real logistics route carries it");
  perf.queryMs = await page.evaluate(() => window.__sov.metrics.queryMs);

  // PROOF inspection of the consequence: claim → offer → acceptance → agreement.
  await page.getByRole("button", { name: "Proof", exact: true }).click();
  const proofLens = page.getByRole("region", { name: "proof lens" });
  await proofLens.getByText("Agreement", { exact: true }).waitFor({ timeout: 30_000 });
  check(/decided ALLOW/.test(await proofLens.innerText()), "the Proof lens shows the acceptance and the kernel's decision");
  await page.getByRole("button", { name: "Space", exact: true }).click();

  // Reload: the World is persistent. The agreement, its proof and the reached Horizon survive.
  const digestBeforeReload = await page.evaluate(() => window.__sov.digest());
  await page.reload();
  await horizon.waitFor({ timeout: 120_000 });
  await page.waitForFunction(() => (window.__sov?.scene()?.renderedRefs().length ?? 0) > 0, null, { timeout: 120_000 });
  const digestAfterReload = await page.evaluate(() => window.__sov.digest());
  check(digestAfterReload.digest === digestBeforeReload.digest, "after reload the browser's kernel holds exactly the same canonical state");
  const stillCommitted = await page.evaluate((ref) => window.__sov.view().markers.find((m) => m.ref === ref)?.state, halden);
  check(stillCommitted === "committed", "after reload Halden still shows the agreement");
  await page.getByRole("button", { name: "Cause", exact: true }).click();
  await page.getByRole("region", { name: "Horizon" }).getByText(/Reached:/).waitFor({ timeout: 30_000 });
  check(true, "after reload the Horizon starts from the reached goal");
  await page.getByRole("button", { name: "Space", exact: true }).click();

  // 7. The steward projection: SOV operating SOV, read with the steward's authority.
  await page.getByRole("button", { name: "Steward", exact: true }).click();
  const steward = page.getByRole("region", { name: "Steward view" });
  await steward.getByText("Build proposals").waitFor({ timeout: 30_000 });
  const stewardText = await steward.innerText();
  const closedTasks = (stewardText.match(/Reconcile payment/g) ?? []).length;
  check(closedTasks === (manifest.operations?.tasks.length ?? 0) && closedTasks > 0, `steward sees ${closedTasks} operational tasks, worked and verified by different parties`);
  check(/CLASS A/.test(stewardText) && /not built yet/i.test(stewardText), "steward sees the Class A proposal and what is not built yet");
  await page.getByRole("button", { name: "Steward", exact: true }).click();
  check(errors.length === 0, `no page or console errors${errors.length ? `: ${errors.slice(0, 3).join(" | ")}` : ""}`);

  // 8. Phone width: same model, no overflow, nothing covering identity.
  const phone = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  await phone.goto(url);
  await phone.getByText("Who should represent you in SOV?").waitFor({ timeout: 120_000 });
  await phone.getByRole("button", { name: /Keep it abstract/ }).click();
  await phone.getByPlaceholder("What do you want to make real?").waitFor();
  const layout = await phone.evaluate(() => {
    const h = document.querySelector("header")?.getBoundingClientRect();
    const n = document.querySelector('nav[aria-label="Lenses"]')?.getBoundingClientRect();
    return { overflow: document.documentElement.scrollWidth > window.innerWidth, overlap: !!h && !!n && h.bottom > n.top && h.top < n.bottom };
  });
  check(!layout.overflow && !layout.overlap, "phone layout: no overflow, lens bar clear of identity");
} finally {
  await browser.close();
  server.kill();
}

// Performance: record, compare, never fail on timing.
Object.assign(perf, { generationMs: manifest.metrics.generationMs, snapshotBytes: manifest.metrics.snapshotBytes, events: manifest.arcadia.tables.events });
mkdirSync(join(root, ".browser-tests"), { recursive: true });
writeFileSync(join(root, ".browser-tests/world-metrics.json"), JSON.stringify(perf, null, 2));
const baselinePath = join(root, "perf/world-baseline.json");
if (process.argv.includes("--update-baseline")) {
  mkdirSync(join(root, "perf"), { recursive: true });
  writeFileSync(baselinePath, JSON.stringify({ recorded: new Date().toISOString(), environment: "headless Chromium, SwiftShader (software WebGL)", metrics: perf }, null, 2) + "\n");
  console.log("baseline updated");
} else if (existsSync(baselinePath)) {
  const baseline = JSON.parse(readFileSync(baselinePath, "utf8")).metrics;
  for (const [key, value] of Object.entries(perf)) {
    const before = baseline[key];
    if (typeof value !== "number" || typeof before !== "number") continue;
    const worse = key === "fps" ? value < before * 0.6 : value > before * 1.5 + 250;
    if (worse) console.log(`warn regression: ${key} ${value} (baseline ${before})`);
  }
}
console.log(`metrics ${JSON.stringify(perf)}`);
if (failures.length) {
  console.error(`\n${failures.length} check(s) failed`);
  process.exit(1);
}
console.log("\nworld: all checks passed");
